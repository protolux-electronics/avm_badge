  101110100111001111000
  100000100100011000000
  111111101000111110101
  """

  @repository """
  111111100111100010111101001111111
  100000100110100110100000001000001
  101110101110001110010100001011101
  101110101111100100100010101011101
  101110101101111111001101001011101
